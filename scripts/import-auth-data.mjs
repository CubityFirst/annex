#!/usr/bin/env node
// One-time copy of Annex-owned data from cubedocs-auth into cubedocs-main.
// See scripts/lib/auth-import.mjs for what is copied and why.
//
// Usage:
//   node scripts/import-auth-data.mjs <cubedocs-auth export .sql | local .sqlite> [--out <file>]
//
// Remote cutover (the user runs these; nothing here touches a database):
//   npx wrangler d1 export cubedocs-auth --remote --output migration-data/cubedocs-auth.sql
//   node scripts/import-auth-data.mjs migration-data/cubedocs-auth.sql --out migration-data/annex-import.sql
//   npx wrangler d1 execute cubedocs-main --remote --file migration-data/annex-import.sql
//
// Local dev: point it at the auth DB's sqlite file under
// .wrangler/state/v3/d1/miniflare-D1DatabaseObject/ (or a local export), then
// apply the output with `node scripts/d1-local.mjs main --file <out>`.
//
// The output only INSERTs (OR IGNORE), so it is safe to re-run, but a re-run
// never refreshes rows that already exist. migration-data/ holds personal
// data: delete it after the cutover.

import { DatabaseSync } from "node:sqlite";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { buildImportStatements } from "./lib/auth-import.mjs";

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const outFile = outIdx >= 0 ? args[outIdx + 1] : "migration-data/annex-import.sql";
const input = args.find((a, i) => !a.startsWith("--") && i !== outIdx + 1);
if (!input) {
  console.error("Usage: node scripts/import-auth-data.mjs <cubedocs-auth .sql export | .sqlite file> [--out <file>]");
  process.exit(1);
}

let db;
if (/\.sql$/i.test(input)) {
  db = new DatabaseSync(":memory:");
  db.exec(readFileSync(input, "utf8"));
} else {
  db = new DatabaseSync(resolve(input), { readOnly: true });
}

const { statements, counts } = buildImportStatements(db);
db.close();

mkdirSync(dirname(resolve(outFile)), { recursive: true });
writeFileSync(
  outFile,
  [
    "-- Generated by scripts/import-auth-data.mjs. Apply to cubedocs-main AFTER",
    "-- migration 0065_add_identity_mirror.sql. Contains personal data.",
    ...statements,
    "",
  ].join("\n"),
);

console.log(`Wrote ${statements.length} statements to ${outFile}`);
for (const [table, n] of Object.entries(counts)) console.log(`  ${table.padEnd(24)} ${n}`);
